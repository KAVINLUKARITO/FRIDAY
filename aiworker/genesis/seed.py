def check_environment() -> Tuple[bool, str]:
    """Verify environment can run AIWorker."""
    # Check Python version
    if sys.version_info < (3, 8):
        return False, f"Python 3.8+ required, got {sys.version_info}"
    
    # Check disk space (rough estimate)
    try:
        stat = os.statvfs('.')
        free_mb = (stat.f_bavail * stat.f_frsize) / (1024 * 1024)
        if free_mb < 1000:
            return False, f"Insufficient disk: {free_mb:.0f}MB free"
    except Exception:
        pass
    
    # Check ollama
    try:
        subprocess.run(['ollama', '--version'], capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        print("Warning: ollama not found. Install from ollama.ai")
    
    return True, "Environment OK"

def bootstrap_phase(phase_num: int, modules: List[str]) -> bool:
    """Bootstrap one phase of AIWorker."""
    print(f"\n{'='*50}")
    print(f"BOOTSTRAPPING PHASE {phase_num}")
    print(f"{'='*50}")
    
    for module_name in modules:
        print(f"\nGenerating module: {module_name}")
        
        # Try to fetch from Ark first
        code = fetch_module(module_name)
        
        # Fallback to local generation
        if code is None:
            print(f"Fetching failed, generating locally...")
            if module_name == 'config':
                code = generate_config_module()
            elif module_name == 'safety_cage':
                code = generate_safety_module()
            else:
                spec = f"Module {module_name} for AIWorker"
                code = generate_module(module_name, spec)
        
        # Validate
        valid, reason = validate_code(code)
        if not valid:
            print(f"Validation failed: {reason}")
            continue
        
        # Write module
        path = write_module(module_name, code)
        print(f"Written: {path}")
        
        # Verify import
        try:
            __import__(f"aiworker.{module_name}")
            print(f"Import verified: aiworker.{module_name}")
        except ImportError as e:
            print(f"Import failed: {e}")
    
    return True

def verify_system() -> Dict[str, Any]:
    """Verify reconstructed system."""
    blueprint = get_blueprint()
    results = {
        "modules_checked": 0,
        "modules_valid": 0,
        "modules_missing": [],
        "modules_modified": []
    }
    
    base_dir = Path("aiworker")
    for name, info in blueprint.get("modules", {}).items():
        results["modules_checked"] += 1
        module_path = base_dir / f"{name}.py"
        
        if not module_path.exists():
            results["modules_missing"].append(name)
            continue
        
        code = module_path.read_text()
        expected_hash = info.get("hash", "")
        
        if expected_hash != "placeholder":
            if verify_hash(code, expected_hash):
                results["modules_valid"] += 1
            else:
                results["modules_modified"].append(name)
        else:
            results["modules_valid"] += 1
    
    return results

# ============ MAIN ============
def print_status():
    """Print current system status."""
    print(f"\n{'='*50}")
    print(f"AIWorker Seed v{VERSION}")
    print(f"{'='*50}")
    
    env_ok, env_msg = check_environment()
    print(f"Environment: {env_msg}")
    
    blueprint = get_blueprint()
    print(f"Blueprint: {len(blueprint.get('modules', {}))} modules defined")
    
    base_dir = Path("aiworker")
    if base_dir.exists():
        modules = list(base_dir.glob("*.py")) + list(base_dir.glob("*/*.py"))
        modules = [m for m in modules if m.name != "__init__.py"]
        print(f"Installed: {len(modules)} modules")
    else:
        print("Installed: None (run 'bootstrap' first)")
    
    kill_switch = Path(".aiworker_kill")
    print(f"Kill switch: {'ACTIVE' if kill_switch.exists() else 'inactive'}")
    print(f"{'='*50}\n")

def main():
    """Entry point."""
    args = sys.argv[1:] if len(sys.argv) > 1 else ['status']
    command = args[0]
    
    if command == 'bootstrap':
        env_ok, env_msg = check_environment()
        if not env_ok:
            print(f"Environment check failed: {env_msg}")
            sys.exit(1)
        
        print("Starting AIWorker bootstrap...")
        
        # Phase 1: Foundation
        bootstrap_phase(1, ['config', 'safety_cage', 'engine'])
        
        # Phase 2: Integration
        bootstrap_phase(2, ['mcp', 'self_modify', 'state_handlers'])
        
        # Phase 3: Production
        bootstrap_phase(3, ['telemetry', 'health', 'backup'])
        
        print("\n" + "="*50)
        print("Bootstrap complete!")
        print("Run 'python seed.py verify' to check system")
        print("Run 'python seed.py self-improve' to begin")
        print("="*50)
    
    elif command == 'verify':
        results = verify_system()
        print(f"\nVerification Results:")
        print(f"  Modules checked: {results['modules_checked']}")
        print(f"  Modules valid: {results['modules_valid']}")
        if results['modules_missing']:
            print(f"  Missing: {', '.join(results['modules_missing'])}")
        if results['modules_modified']:
            print(f"  Modified: {', '.join(results['modules_modified'])}")
    
    elif command == 'self-improve':
        print("Starting self-improvement loop...")
        print("(This would delegate to aiworker.main in full system)")
        
        # Check if full system exists
        main_path = Path("aiworker/main.py")
        if main_path.exists():
            print("Handing off to full AIWorker system...")
            os.execvp(sys.executable, [sys.executable, "-m", "aiworker.main", "self-improve"])
        else:
            print("Full system not found. Run 'bootstrap' first.")
    
    elif command == 'status':
        print_status()
    
    elif command == 'help':
        print(__doc__)
    
    else:
        print(f"Unknown command: {command}")
        print("Use: bootstrap, verify, self-improve, status, help")
        sys.exit(1)

if __name__ == "__main__":
    main()

