# ============ SELF-MODIFICATION ============
def write_module(name: str, code: str) -> Path:
    """Write module to aiworker/ directory."""
    base_dir = Path("aiworker")
    parts = name.split('.')
    
    if len(parts) > 1:
        module_dir = base_dir / parts[0]
        module_dir.mkdir(parents=True, exist_ok=True)
        file_path = module_dir / f"{parts[1]}.py"
    else:
        file_path = base_dir / f"{name}.py"
    
    base_dir.mkdir(exist_ok=True)
    
    with open(file_path, 'w') as f:
        f.write(code)
    
    # Create __init__.py if needed
    init_file = file_path.parent / "__init__.py"
    if not init_file.exists():
        init_file.write_text('"""AIWorker module."""\n')
    
    return file_path

def backup_seed() -> Path:
    """Create backup of seed.py before modification."""
    seed_path = Path(__file__)
    backup_path = seed_path.with_suffix('.py.backup')
    backup_path.write_text(seed_path.read_text())
    return backup_path

def integrate_self(code: str) -> bool:
    """Add capability to seed itself (careful)."""
    valid, reason = validate_code(code)
    if not valid:
        print(f"Validation failed: {reason}")
        return False
    
    if not human_confirm("Self-modification", code[:1000]):
        print("Self-modification denied")
        return False
    
    backup = backup_seed()
    print(f"Backup created: {backup}")
    
    seed_path = Path(__file__)
    with open(seed_path, 'a') as f:
        f.write(f"\n# Self-modification: {time.time()}\n")
        f.write(code)
    
    print("Self-modification applied")
    return True

# ============ DOWNLOAD ============
def fetch_module(name: str) -> Optional[str]:
    """Download module from Ark."""
    url = f"{ARK_URL}/modules/{name}.py"
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            code = response.read().decode('utf-8')
            valid, reason = validate_code(code)
            if valid:
                return code
            print(f"Downloaded code invalid: {reason}")
            return None
    except urllib.error.URLError as e:
        print(f"Download failed: {e}")
        return None
    except Exception as e:
        print(f"Download error: {e}")
        return None

def verify_hash(code: str, expected_hash: str) -> bool:
    """Verify code hash matches expected."""
    actual = hashlib.sha256(code.encode()).hexdigest()[:16]
    return actual == expected_hash

