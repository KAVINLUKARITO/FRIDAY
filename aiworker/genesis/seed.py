# ============ LLM INTERFACE ============
def llm(prompt: str, model: str = OLLAMA_MODEL, timeout: int = 60) -> str:
    """Call local LLM via ollama subprocess."""
    try:
        cmd = ["ollama", "run", model, prompt]
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout
        )
        if result.returncode == 0:
            return result.stdout.strip()
        return f"# Error: {result.stderr}"
    except FileNotFoundError:
        return "# Error: ollama not found. Install from ollama.ai"
    except subprocess.TimeoutExpired:
        return "# Error: LLM call timed out"
    except Exception as e:
        return f"# Error: {e}"

# ============ SAFETY ============
def validate_code(code: str) -> Tuple[bool, str]:
    """AST parse and forbidden pattern check."""
    # Check forbidden patterns
    for pattern in FORBIDDEN_PATTERNS:
        if pattern in code:
            return False, f"Forbidden pattern: {pattern}"
    
    # AST validation
    try:
        tree = ast.parse(code)
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                # Check for dangerous calls
                if isinstance(node.func, ast.Name):
                    if node.func.id in ['eval', 'exec', 'compile', '__import__']:
                        return False, f"Forbidden function: {node.func.id}"
                # Check for subprocess with shell
                if isinstance(node.func, ast.Attribute):
                    if node.func.attr in ['system', 'popen']:
                        return False, f"Forbidden: {node.func.attr}"
        return True, "Valid"
    except SyntaxError as e:
        return False, f"Syntax error: {e}"

def human_confirm(action: str, detail: str) -> bool:
    """Prompt for confirmation in TTY, auto-deny elsewhere."""
    if not sys.stdin.isatty():
        print(f"[NON-TTY] Would ask: {action}")
        print(f"Detail: {detail}")
        return False
    
    print(f"\n{'='*50}")
    print(f"ACTION: {action}")
    print(f"{'='*50}")
    print(detail)
    print(f"{'='*50}")
    print(f"Waiting {SAFETY_PAUSE} seconds...")
    time.sleep(SAFETY_PAUSE)
    
    response = input("Approve? (yes/no): ").strip().lower()
    return response == 'yes'

def rate_limit_check() -> bool:
    """Enforce generation rate limit."""
    now = time.time()
    global _generation_times
    _generation_times = [t for t in _generation_times if now - t < 60]
    if len(_generation_times) >= MAX_GENERATIONS_PER_MINUTE:
        return False
    _generation_times.append(now)
    return True

# ============ CODE GENERATION ============
